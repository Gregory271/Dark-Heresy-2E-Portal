import assert from 'node:assert/strict';
import {characteristicValue,skillRows,weaponModes,damagePool,updateCombatField,armourLocations} from '../foundry-module/dh2-portal/scripts/portal-combat.mjs';
globalThis.game={user:{isGM:false}};
const changes=[];
const actor={isOwner:true,system:{characteristics:{strength:{base:40,total:20,unnatural:2,short:'S'},ballisticSkill:{base:45,advance:1,modifier:5,short:'BS'},agility:{total:35,short:'Ag'}},skills:{dodge:{label:'Dodge',characteristic:'Ag',advance:2,current:45},lore:{label:'Lore',isSpecialist:true,characteristic:'Ag',specialities:{one:{label:'One',advance:1},two:{label:'Two',advance:0}}}}},update:async c=>changes.push(c)};
assert.equal(characteristicValue(actor,'strength'),20,'Use fatigue/effect-adjusted native total');
assert.equal(characteristicValue(actor,'ballisticSkill'),55);
assert.equal(skillRows(actor).length,2);
assert.equal(skillRows(actor)[0].target,45);
const protectionActor={system:{characteristics:{toughness:{total:35,bonus:5}},armour:{head:{total:12,value:4,toughnessBonus:5,traitBonus:3}}},items:[{type:'armour',system:{equipped:true,armourPoints:{body:4,leftArm:2}}},{type:'armour',system:{equipped:false,armourPoints:{body:9}}}]};
const locations=armourLocations(protectionActor);
assert.equal(locations.length,6);
assert.equal(locations.find(l=>l.id==='head').total,12,'Preserve native trait and effect protection');
assert.equal(locations.find(l=>l.id==='head').extra,'+3 other');
assert.equal(locations.find(l=>l.id==='body').total,9,'Only equipped armour counts');
assert.equal(locations.find(l=>l.id==='rightLeg').total,5,'Unarmoured locations retain Toughness Bonus');
const gun={system:{class:'Basic',damage:'1d10+3',rateOfFire:{single:1,burst:3,full:0}}};
assert.deepEqual(weaponModes(gun).map(m=>m.id),['standard','semi','called']);
const melee={system:{class:'Melee',damage:'1d10+2'}};
assert.equal(damagePool(actor,melee).damage.modifier,6);
melee.flags={dh2CharacterBuilder:{printedDamage:'1d10+8',weaponQualities:'Tearing, Primitive (7)'}};
assert.deepEqual(damagePool(actor,melee),{quantity:2,sides:10,damage:{keep:1,modifier:8,primitive:7}});
assert.equal(damagePool(actor,melee,'2d10+3-1').damage.modifier,2,'Custom formula never re-adds SB');
assert.throws(()=>damagePool(actor,melee,'alert(1)'));
await updateCombatField(actor,'system.wounds.value',5);
await updateCombatField(actor,'system.integrity.value',14);
await updateCombatField(actor,'flags.dh2CharacterBuilder.combatModifier',-20);
assert.equal(changes.length,3);
for(const [key,value] of [['ownership.default',3],['system.fatigue.value',-1],['system.wounds.value',''],['system.wounds.max',Infinity]])await assert.rejects(updateCombatField(actor,key,value));
await assert.rejects(updateCombatField({...actor,isOwner:false},'name','No'));
console.log('Portal combat QA passed: adjusted targets, skill specialities, modes, damage, validated persistence and permissions.');
