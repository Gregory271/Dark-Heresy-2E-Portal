import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const source=readFileSync(new URL('../hosted/src/main.js',import.meta.url),'utf8');
const extract=name=>{const start=source.indexOf(`function ${name}(`);assert(start>=0);return source.slice(start,source.indexOf('\n}\n',start)+2);};
const context=vm.createContext({});
vm.runInContext(['inventoryGroup','inventoryMatches'].map(extract).join('\n'),context);
assert.equal(context.inventoryGroup('Weapon Mods'),'Modifications');
assert.equal(context.inventoryGroup('Consumables'),'Gear');
assert.equal(context.inventoryGroup('Weapons'),'Weapons');
const state={query:' LAS ',group:'Weapons',equippedOnly:false};
assert(context.inventoryMatches('Laspistol Background','Weapons',false,state));
assert(!context.inventoryMatches('Las armour','Armour',true,state));
state.equippedOnly=true;
assert(!context.inventoryMatches('Laspistol','Weapons',false,state));
assert(context.inventoryMatches('Laspistol','Weapons',true,state));
state.query='';state.group='All';state.equippedOnly=false;
assert(context.inventoryMatches('Unlinked starting item','Gear',false,state));
assert(!source.includes('<span>Readied</span>'));
assert(!source.includes('<span>Worn / in use</span>'));
console.log('Inventory index: categories, combined filters, case-insensitive search, unlinked gear and consistent labels passed.');
