import assert from 'node:assert/strict';
import {ammunitionCost, setAmmunition, reloadAmmunition} from '../foundry-module/dh2-portal/scripts/ammunition.mjs';
import {rollSheetDice} from '../foundry-module/dh2-portal/scripts/sheet-chat.mjs';
globalThis.game={user:{isGM:false}};
globalThis.foundry={};
