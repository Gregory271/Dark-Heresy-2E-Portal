const weapon={id:'gun',type:'weapon',name:'Autogun',system:{class:'Basic',clip:{value:30,max:30},rateOfFire:{single:1,burst:3,full:10}},flags:{},async update(data){if('system.clip.value'in data)this.system.clip.value=data['system.clip.value'];if('flags.dh2Ammo.reserve'in data)this.flags.dh2Ammo={reserve:data['flags.dh2Ammo.reserve']};}};
